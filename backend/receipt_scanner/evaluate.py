import os
import json
import re
import torch
from PIL import Image
from transformers import DonutProcessor, VisionEncoderDecoderModel

# ==========================================
# 1. CONFIGURATION
# ==========================================
MODEL_PATH = r"C:\Users\parth\Desktop\Parthyo\Expense Tracker\Expense_Tracker\backend\receipt_scanner\donut-receipt-parser" # Your downloaded trained model
TEST_DATA_DIR = r"C:\Users\parth\Desktop\Parthyo\Expense Tracker\Expense_Tracker\backend\receipt_scanner\test_dataset"      # The test dataset generated by prepare_sroie.py


def main():
    print("Loading your trained model...")
    # Check for Nvidia (cuda), Intel Arc (xpu), or fallback to CPU
    device = "cuda" if torch.cuda.is_available() else ("xpu" if hasattr(torch, "xpu") and torch.xpu.is_available() else "cpu")
    print(f"Running evaluation on: {device.upper()}")

    try:
        processor = DonutProcessor.from_pretrained(MODEL_PATH)
        model = VisionEncoderDecoderModel.from_pretrained(MODEL_PATH)
        model.to(device)
        model.eval() # Set model to evaluation mode
    except Exception as e:
        print(f"Error loading model from {MODEL_PATH}. Did you download it from Colab? Error: {e}")
        return

    metadata_path = os.path.join(TEST_DATA_DIR, "metadata.jsonl")
    if not os.path.exists(metadata_path):
        print(f"Error: {metadata_path} not found. Please run your prepare_sroie.py script on the test folder first!")
        return

    # Track correct predictions
    exact_matches = {"brand": 0, "category": 0, "date": 0, "amount": 0}
    total_receipts = 0

    print(f"Starting evaluation of receipts in {TEST_DATA_DIR}...\n")
    
    with open(metadata_path, "r", encoding="utf-8") as f:
        for line in f:
            # 1. Load the ground truth data
            data = json.loads(line)
            image_name = data["file_name"]
            ground_truth = json.loads(data["ground_truth"])
            
            image_path = os.path.join(TEST_DATA_DIR, image_name)
            if not os.path.exists(image_path):
                continue
                
            # 2. Process Image
            image = Image.open(image_path).convert("RGB")
            pixel_values = processor(image, return_tensors="pt").pixel_values.to(device)
            
            task_prompt = "<s_receipt>"
            decoder_input_ids = processor.tokenizer(
                task_prompt, 
                add_special_tokens=False, 
                return_tensors="pt"
            ).input_ids.to(device)

            # 3. Generate Prediction
            with torch.no_grad():
                outputs = model.generate(
                    pixel_values,
                    decoder_input_ids=decoder_input_ids,
                    max_length=model.decoder.config.max_position_embeddings,
                    pad_token_id=processor.tokenizer.pad_token_id,
                    eos_token_id=processor.tokenizer.eos_token_id,
                    use_cache=True,
                    num_beams=1,
                    bad_words_ids=[[processor.tokenizer.unk_token_id]],
                    return_dict_in_generate=True,
                )

            # 4. Clean and Decode Output
            sequence = processor.batch_decode(outputs.sequences)[0]
            sequence = sequence.replace(processor.tokenizer.eos_token, "").replace(processor.tokenizer.pad_token, "")
            raw_sequence = re.sub(r"<.*?>", "", sequence, count=1).strip()  
            
            predicted_data = processor.token2json(raw_sequence)
            
            # --- FIX: Unwrap nested 'receipt' key if it exists ---
            if not isinstance(predicted_data, dict):
                predicted_data = {}
            elif "receipt" in predicted_data and isinstance(predicted_data["receipt"], dict):
                predicted_data = predicted_data["receipt"]

            # 5. Compare with Ground Truth (Case-Insensitive Exact Match)
            for key in exact_matches.keys():
                pred_val = str(predicted_data.get(key, "")).strip().lower()
                true_val = str(ground_truth.get(key, "")).strip().lower()
                
                # Make sure we don't count empty strings as a match
                if pred_val == true_val and true_val != "":
                    exact_matches[key] += 1
                    
            total_receipts += 1
            
            # --- DEBUGGING OUTPUT FOR THE FIRST 5 RECEIPTS ---
            if total_receipts <= 5:
                print(f"--- Receipt {total_receipts} Debug ({image_name}) ---")
                print(f"Raw Output Token Sequence: {raw_sequence}")
                print(f"Parsed Predicted JSON:     {predicted_data}")
                print(f"Actual Ground Truth:       {ground_truth}")
                print("--------------------------------------------------\n")
            
            if total_receipts % 10 == 0:
                print(f"Processed {total_receipts} receipts...")

    # ==========================================
    # 6. PRINT FINAL METRICS
    # ==========================================
    if total_receipts == 0:
        print("\nNo receipts were processed. Check your dataset paths.")
        return

    print("\n==========================================")
    print(f"=== EVALUATION RESULTS (Total: {total_receipts}) ===")
    print("==========================================")
    
    for key, correct_count in exact_matches.items():
        accuracy = (correct_count / total_receipts) * 100
        print(f" {key.upper():<10} Accuracy: {accuracy:>6.2f}% ({correct_count}/{total_receipts})")
    print("==========================================\n")

if __name__ == "__main__":
    main()